from __future__ import annotations

import re
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MASTERY_PATH = ROOT / "MASTERY.md"
LINK_PATTERN = re.compile(r"^\d+\. \[[^]]+\]\(([^)]+)\)$")


def is_core(path: str) -> bool:
    return path.startswith(("serving/", "tools/")) or path in {
        "benchmarks/models.py",
        "harnesses/contracts.py",
        "tracing/events.py",
    }


def is_harness(path: str) -> bool:
    return path.startswith("harnesses/") or path.startswith("tracing/")


def is_measurement(path: str) -> bool:
    return path.startswith(("evaluation/", "profiling/"))


def is_experiment(path: str) -> bool:
    return path.startswith("optimization/") or path in {
        "benchmarks/cache_experiment.py",
        "benchmarks/concurrency_experiment.py",
        "benchmarks/quantization_experiment.py",
    }


def is_product(path: str) -> bool:
    return path.startswith(("backend/", "frontend/", "tests/")) or path in {
        "README.md",
        "ARCHITECTURE.md",
        "RESULTS.md",
    }


BUNDLES: dict[str, Callable[[str], bool]] = {
    "OPTIMO_CODEBOOK.md": lambda path: True,
    "OPTIMO_CORE.md": is_core,
    "OPTIMO_HARNESSES.md": is_harness,
    "OPTIMO_MEASUREMENT.md": is_measurement,
    "OPTIMO_EXPERIMENTS.md": is_experiment,
    "OPTIMO_PRODUCT.md": is_product,
}


def mastery_files() -> list[str]:
    paths = []
    for line in MASTERY_PATH.read_text(encoding="utf-8").splitlines():
        match = LINK_PATTERN.match(line)
        if match:
            paths.append(match.group(1))
    if not paths:
        raise RuntimeError("MASTERY.md does not contain numbered Markdown file links")
    return paths


def language_for(path: str) -> str:
    return {
        ".md": "markdown",
        ".py": "python",
        ".ts": "typescript",
        ".tsx": "tsx",
        ".js": "javascript",
        ".jsx": "jsx",
    }.get(Path(path).suffix.lower(), "text")


def anchor_for(index: int, path: str) -> str:
    normalized = re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")
    return f"{index}-{normalized}"


def render(title: str, paths: list[str]) -> str:
    lines = [
        f"# {title}",
        "",
        "> Generated by `py scripts/build_codebook.py`. Do not edit this file directly.",
        "> Edit the original source file, then regenerate the codebook.",
        "",
        "## Contents",
        "",
    ]
    for index, path in enumerate(paths, start=1):
        lines.append(f"{index}. [{path}](#{anchor_for(index, path)})")

    for index, path in enumerate(paths, start=1):
        source_path = ROOT / path
        if not source_path.is_file():
            raise FileNotFoundError(f"Mastery source does not exist: {path}")
        source = source_path.read_text(encoding="utf-8").rstrip()
        lines.extend(
            [
                "",
                f'<a id="{anchor_for(index, path)}"></a>',
                "",
                f"## {index}. `{path}`",
                "",
                f"Source: [{path}]({path})",
                "",
                f"````{language_for(path)}",
                source,
                "````",
            ]
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    paths = mastery_files()
    for output_name, include in BUNDLES.items():
        selected = [path for path in paths if include(path)]
        title = output_name.removesuffix(".md").replace("_", " ").title()
        (ROOT / output_name).write_text(render(title, selected), encoding="utf-8")
        print(f"generated {output_name}: {len(selected)} files")


if __name__ == "__main__":
    main()
